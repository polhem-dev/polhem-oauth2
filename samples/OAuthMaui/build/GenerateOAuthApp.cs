// Run by OAuthApp.targets as a file-based program: dotnet run GenerateOAuthApp.cs -- <config> <output directory> <default scheme>
//
// OAuthConfig.json holds the client secrets of the desktop and web clients, so it is never packaged as a whole. This program
// copies an allowlist of fields into OAuthApp.json, which the application carries, and derives the callback schemes each
// platform must register from the redirect URIs. No ClientSecret is ever written.

using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

string configFile = args[0];
string outputDirectory = args[1];
string defaultScheme = args[2];

var clientFields = new[] { "ClientId", "RedirectUri", "Scopes", "UsePkce" };
var sharedFields = new[] { "Domain", "Tenant", "AuthorizationServerId" };
var clientTypes = new[] { "iOS", "Android", "Desktop", "Web" };
var appleSchemes = new SortedSet<string>(StringComparer.Ordinal) { defaultScheme };
var androidSchemes = new SortedSet<string>(StringComparer.Ordinal) { defaultScheme };
var providersOut = new JsonObject();
JsonObject? relayOut = null;

if (File.Exists(configFile))
{
    var root = JsonNode.Parse(File.ReadAllText(configFile)) as JsonObject;
    var providers = root?["Providers"] as JsonObject;
    if (providers != null)
    {
        foreach (var provider in providers)
        {
            var section = provider.Value as JsonObject;
            if (section == null)
                continue;
            var providerOut = new JsonObject();
            foreach (var field in section)
            {
                if (sharedFields.Contains(field.Key, StringComparer.OrdinalIgnoreCase))
                {
                    providerOut[field.Key] = field.Value?.DeepClone();
                    continue;
                }
                var client = field.Value as JsonObject;
                string clientType = field.Key;
                if (client == null || !clientTypes.Contains(clientType, StringComparer.OrdinalIgnoreCase))
                    continue;
                string? clientId = client["ClientId"]?.GetValue<string>();
                if (string.IsNullOrWhiteSpace(clientId))
                    continue;
                var clientOut = new JsonObject();
                // A web client only tells the application that the back end can relay this provider.
                string[] allowed = clientType.Equals("Web", StringComparison.OrdinalIgnoreCase) ? new[] { "ClientId" } : clientFields;
                foreach (var value in client)
                {
                    if (allowed.Contains(value.Key, StringComparer.OrdinalIgnoreCase))
                        clientOut[value.Key] = value.Value?.DeepClone();
                }
                providerOut[clientType] = clientOut;
                if (Uri.TryCreate(client["RedirectUri"]?.GetValue<string>(), UriKind.Absolute, out var redirect) && redirect.Scheme != "https")
                {
                    if (clientType.Equals("iOS", StringComparison.OrdinalIgnoreCase))
                        appleSchemes.Add(redirect.Scheme);
                    else if (clientType.Equals("Android", StringComparison.OrdinalIgnoreCase))
                        androidSchemes.Add(redirect.Scheme);
                }
            }
            if (providerOut.Any(field => !sharedFields.Contains(field.Key, StringComparer.OrdinalIgnoreCase)))
                providersOut[provider.Key] = providerOut;
        }
    }

    var relay = root?["AppRelay"] as JsonObject;
    if (relay != null)
    {
        relayOut = new JsonObject
        {
            ["BackendUrl"] = relay["BackendUrl"]?.DeepClone(),
            ["RedirectUri"] = relay["RedirectUri"]?.DeepClone()
        };
        if (Uri.TryCreate(relay["RedirectUri"]?.GetValue<string>(), UriKind.Absolute, out var relayRedirect))
        {
            appleSchemes.Add(relayRedirect.Scheme);
            androidSchemes.Add(relayRedirect.Scheme);
        }
    }
}
else
{
    Console.WriteLine("OAuthConfig.json : warning OAUTHMAUI1: " + "OAuthConfig.json was not found, so the application carries no OAuth2 settings. Copy OAuthConfig.example.json in the repository root to OAuthConfig.json and fill it in.");
}

Directory.CreateDirectory(outputDirectory);
var output = new JsonObject { ["Providers"] = providersOut };
if (relayOut != null)
    output["AppRelay"] = relayOut;
WriteIfChanged(Path.Combine(outputDirectory, "OAuthApp.json"), output.ToJsonString(new JsonSerializerOptions { WriteIndented = true }));

var activity = new StringBuilder();
activity.AppendLine("// <auto-generated> by OAuthApp.targets from the redirect URIs in OAuthConfig.json. </auto-generated>");
activity.AppendLine("#if ANDROID");
activity.AppendLine("namespace OAuthMaui;");
activity.AppendLine();
activity.AppendLine("[Android.App.Activity(NoHistory = true, LaunchMode = Android.Content.PM.LaunchMode.SingleTop, Exported = true)]");
activity.AppendLine("[Android.App.IntentFilter(new[] { Android.Content.Intent.ActionView },");
activity.AppendLine("    Categories = new[] { Android.Content.Intent.CategoryDefault, Android.Content.Intent.CategoryBrowsable },");
activity.AppendLine("    DataSchemes = new[] { " + string.Join(", ", androidSchemes.Select(scheme => "\"" + scheme + "\"")) + " })]");
activity.AppendLine("public class OAuthCallbackActivity : Microsoft.Maui.Authentication.WebAuthenticatorCallbackActivity");
activity.AppendLine("{");
activity.AppendLine("}");
activity.AppendLine("#endif");
WriteIfChanged(Path.Combine(outputDirectory, "OAuthCallbackActivity.g.cs"), activity.ToString());

var plist = new StringBuilder();
plist.AppendLine("<?xml version=\"1.0\" encoding=\"UTF-8\"?>");
plist.AppendLine("<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">");
plist.AppendLine("<plist version=\"1.0\"><dict><key>CFBundleURLTypes</key><array><dict>");
plist.AppendLine("<key>CFBundleURLName</key><string>OAuth2 callbacks</string><key>CFBundleURLSchemes</key><array>");
foreach (string scheme in appleSchemes)
    plist.AppendLine("<string>" + System.Security.SecurityElement.Escape(scheme) + "</string>");
plist.AppendLine("</array></dict></array></dict></plist>");
WriteIfChanged(Path.Combine(outputDirectory, "OAuthUrlTypes.plist"), plist.ToString());

void WriteIfChanged(string path, string content)
{
    if (!File.Exists(path) || File.ReadAllText(path) != content)
        File.WriteAllText(path, content);
}
      
